// Renames Nirvana to Impera across the repository (ADR 0062). Idempotent: run it again and nothing changes. Every
// branch that was open at the rename runs it on itself, commits, then rebases on main.
//
// Usage: node scripts/rename-impera.mjs            rename, regenerate pnpm-lock.yaml, then pnpm check and pnpm test
//        node scripts/rename-impera.mjs --dry-run  list what would change, touch nothing
// Prettier runs on the changed files after the rename, before the checks.
//
// What stays (ADR 0062 § 2) is never touched: the migrations already written, the past ADRs, the session log and the
// finished task cards, brainstorm/, the Postgres roles nirvana_app and nirvana_admin, the pay engine version
// nirvana-N, the `@nirvana` suffix of calendar event UIDs, the repository URL and Charles's local folder. A line that
// names the old word on purpose (a legacy key read once, the guard against an old variable) carries « ADR 0062 » and
// is left as it is.
import { execFileSync, spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

/** Paths the rename never touches (ADR 0062 § 2.4 and § 2.5). */
const SKIPPED = [
  /^packages\/db\/migrations\//,
  /^docs\/adr\//,
  /^docs\/sessions\/log\//,
  /^docs\/sessions\/LOG\.md$/,
  /^brainstorm\//,
  /^pnpm-lock\.yaml$/, // regenerated by pnpm install
  /^scripts\/rename-impera(\.test)?\.mjs$/,
];

/** Files read as bytes, never as text. */
const BINARY = /\.(png|jpe?g|gif|webp|ico|woff2?|ttf|otf|pdf|zip|gz|age|mp3|mp4|ogg|wav|webm)$/i;

/** A task card is history once its first « Statut : » says done (ADR 0062 § 2.5); an open card is renamed. */
export function finishedCard(text) {
  const status = /^\**Statut\**\s*:\s*\**\s*([a-z_-]+)/im.exec(text);
  return status !== null && status[1] === 'done';
}

/** Whether a tracked path is renamed. `read` gives a file's text, for the task cards. */
export function inScope(path, read) {
  if (SKIPPED.some((pattern) => pattern.test(path)) || BINARY.test(path)) return false;
  if (/^docs\/sessions\/tasks\/.+\.md$/.test(path)) return !finishedCard(read(path));
  return true;
}

/** Names that keep the old word (ADR 0062 § 2), shielded before the replacements and put back after. */
const KEPT = [
  /nirvana_(?:app|admin)\b/g, // Postgres roles, granted by name in applied migrations
  /nirvana-(?=\d|N\b|\\d|\[0-9\])/g, // pay engine version nirvana-N, written in every statement
  /@nirvana(?![\w/-])/g, // suffix of the calendar event UIDs
  /LeyZee\/nirvana/gi, // the repository URL, renamed by Charles in GitHub
  /Projet Nirvana/g, // Charles's local folder, renamed by him after the database switch
  /projetnirvana/g, // the compose project name that folder gives
];

/** French elision before a vowel: « de Nirvana » becomes « d’Impera » (ADR 0062 § 4.1). */
const ELISIONS = [[/(?<!\p{L})([Dd]|[Qq]u|[Jj]usqu|[Ll]orsqu|[Pp]uisqu)e Nirvana/gu, '$1’Impera']];

const CASES = [
  [/NIRVANA/g, 'IMPERA'],
  [/Nirvana/g, 'Impera'],
  [/nirvana/g, 'impera'],
];

/** One line, renamed. */
function renameLine(line) {
  if (line.includes('ADR 0062') || !/nirvana/i.test(line)) return line;
  const shielded = [];
  let text = line;
  for (const pattern of KEPT) {
    text = text.replace(pattern, (match) => {
      shielded.push(match);
      return `\u0000${String(shielded.length - 1)}\u0000`;
    });
  }
  for (const [pattern, replacement] of [...ELISIONS, ...CASES]) text = text.replace(pattern, replacement);
  return text.replace(/\u0000(\d+)\u0000/g, (_, index) => shielded[Number(index)]);
}

/** A file's text, renamed. */
export function renameText(text) {
  return text.split('\n').map(renameLine).join('\n');
}

/** A tracked path, renamed (`brand/nirvana-mark.svg` → `brand/impera-mark.svg`). */
export function renamePath(path) {
  return path.replace(/nirvana/g, 'impera').replace(/Nirvana/g, 'Impera');
}

/** What a renamed text must not contain: an elision the replacements missed. */
export function leftovers(text) {
  return text
    .split('\n')
    .filter((line) => /(?<!\p{L})(de|que|De|Que) Impera/u.test(line))
    .map((line) => line.trim());
}

function git(...args) {
  return execFileSync('git', args, { encoding: 'utf8' });
}

function run(command, args) {
  const result = spawnSync(command, args, { stdio: 'inherit' });
  if (result.status !== 0) {
    console.error(`${command} ${args.join(' ')} a échoué : le renommage n'est pas terminé.`);
    process.exit(result.status ?? 1);
  }
}

// Run from the command line (not when imported by its test).
if (process.argv[1]?.endsWith('rename-impera.mjs') === true) {
  const dryRun = process.argv.includes('--dry-run');
  const read = (path) => readFileSync(path, 'utf8');
  const files = git('ls-files', '-z')
    .split('\0')
    .filter((path) => path !== '');
  const changed = [];
  const problems = [];
  for (const path of files.filter((file) => inScope(file, read))) {
    const before = read(path);
    const after = renameText(before);
    if (after !== before) {
      changed.push(path);
      if (!dryRun) writeFileSync(path, after);
    }
    for (const line of leftovers(after)) problems.push(`${path} : ${line}`);
  }
  const moved = files.filter((path) => inScope(path, read) && renamePath(path) !== path);
  for (const path of moved) if (!dryRun) git('mv', path, renamePath(path));

  console.log(`${String(changed.length)} fichiers modifiés, ${String(moved.length)} renommés.`);
  if (dryRun) {
    for (const path of changed) console.log(`  ${path}`);
    for (const path of moved) console.log(`  ${path} → ${renamePath(path)}`);
  }
  if (problems.length > 0) {
    console.error(`Élision manquée (« de Impera », « que Impera ») :\n${problems.join('\n')}`);
    process.exit(1);
  }
  if (!dryRun) {
    run('pnpm', ['install']);
    // A shorter name can let Prettier join lines it used to wrap.
    if (changed.length > 0)
      run('pnpm', ['exec', 'prettier', '--write', '--ignore-unknown', '--log-level=warn', ...changed]);
    run('pnpm', ['check']);
    run('pnpm', ['test']);
    console.log('Renommage terminé : pnpm check et pnpm test sont verts.');
  }
}
